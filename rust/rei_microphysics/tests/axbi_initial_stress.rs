//! Native physics+independent Python DOP853 endpoint comparison of initial π_ab.
use rei_microphysics::axbi_background::{Cosmology,AxbiBackground,BackgroundFamily};
use rei_microphysics::axbi_stress_background::AxbiInitialStressBackground;
const A0:f64=1.0/21.0;
const A1:f64=0.2;
fn cosm()->Cosmology{Cosmology{
 h0_per_s:2.1842852410855026e-18,omega_m:0.315,omega_r:9.2e-5,
 omega_lambda:0.6849080000000001,
}}
fn bg(q:f64,k:f64)->AxbiInitialStressBackground{
 AxbiInitialStressBackground::new(cosm(),A0,A1,q,k).unwrap()
}
fn approx_rel(a:f64,b:f64,tol:f64){
 assert!((a/b-1.).abs()<=tol,"relative difference {a:e} vs {b:e} > {tol:e}")
}
#[test]
fn initial_pi_independent_and_positive_quadrupole(){
 for &(q,k) in &[(0.0,0.2),(0.005,0.0),(-0.01,-0.2),(0.01,0.5)]{
  let x=bg(q,k);
  let (m,p)=x.angular_moments(0.).unwrap();
  approx_rel(m,1.,2e-13);
  assert!((p-k/15.).abs()<8e-15);
  assert!((x.initial_pi_over_radiation()-k/15.).abs()<1e-16);
 }
 assert!(AxbiInitialStressBackground::new(cosm(),A0,A1,0.,0.501).is_err());
 assert!(AxbiInitialStressBackground::new(cosm(),A0,A1,0.123,0.2).is_err());
}
#[test]
fn collisionless_moment_energy_conservation_derivative(){
 for &(q,k) in &[(0.,-0.2),(0.01,0.),(0.005,0.2)]{
  let x=bg(q,k);
  for &b in &[-0.01,-0.002,0.0,0.002,0.01]{
   let h=2e-5;
   let mp=x.angular_moments(b+h).unwrap().0;
   let mm=x.angular_moments(b-h).unwrap().0;
   let (_,p)=x.angular_moments(b).unwrap();
   let residual=(mp-mm)/(2.0*h)+6.*p;
   assert!(residual.abs()<3e-9,"b={b} q={q} k={k} dM/db+6P={residual:e}");
  }
 }
}
#[test]
fn independent_python_10_signed_cases_source_parity(){
 let raw=include_str!("fixtures/axbi_initial_stress_coupled_10.csv");
 let mut count=0;
 let mut max_b=0_f64;
 let mut max_sigma=0_f64;
 let mut max_t=0_f64;
 for line in raw.lines().skip(1){
  let cols:Vec<_>=line.split(',').collect();
  assert_eq!(cols.len(),7);
  let nums:Vec<f64>=cols.iter().map(|a|a.parse::<f64>().unwrap()).collect();
  let [q,k,t,b,sigma,m,pi]=nums.try_into().unwrap();
  let p=bg(q,k).endpoint(1024).unwrap();
  max_b=max_b.max((p.b-b).abs());
  max_sigma=max_sigma.max((p.s_over_h-sigma).abs());
  max_t=max_t.max((p.elapsed_proper_s/t-1.).abs());
  assert!((p.b-b).abs()<2e-9,"case {q},{k}: b");
  assert!((p.s_over_h-sigma).abs()<2e-9,"case {q},{k}: s/H");
  assert!((p.elapsed_proper_s/t-1.).abs()<5e-10,"case {q},{k}: t");
  assert!((p.radiation_m-m).abs()<1e-11);
  assert!((p.radiation_p/p.radiation_m-pi).abs()<1e-11);
  count+=1;
 }
 assert_eq!(count,10);
 println!("NATIVE_RUST_INITIAL_STRESS_DOP853_10 n={count}, max_delta_b={max_b:e}, max_delta_sH={max_sigma:e}, max_rel_t={max_t:e}");
}
#[test]
fn physical_zero_shear_zero_pi_retains_exact_flrw(){
 let x=bg(0.,0.);
 let traj=x.trajectory(128).unwrap();
 assert_eq!(traj.len(),129);
 for r in &traj{
  assert_eq!(r.b,0.);
  assert_eq!(r.s_per_s,0.);
  assert_eq!(r.s_over_h,0.);
  assert_eq!(r.radiation_m,1.);
  assert_eq!(r.radiation_p,0.);
 }
 let reference=AxbiBackground::new(cosm(),A0,A1,0.,0.,BackgroundFamily::PhysicalDensityFixed,4096).unwrap();
 approx_rel(traj.last().unwrap().elapsed_proper_s,reference.point_at_scale(A1).unwrap().time_s,3e-10);
}
#[test]
fn stress_alone_generates_real_shear_and_q_mirrors_independent(){
 let st=bg(0.,0.2).endpoint(1024).unwrap();
 assert!(st.b>8e-5 && st.s_over_h>5e-5);
 let stneg=bg(0.,-0.2).endpoint(1024).unwrap();
 assert!(stneg.b< -8e-5 && stneg.s_over_h< -5e-5);
 let baseline=bg(0.005,0.).endpoint(1024).unwrap();
 let original=AxbiBackground::new(cosm(),A0,A1,0.,0.005,BackgroundFamily::PhysicalDensityFixed,4096).unwrap().point_at_scale(A1).unwrap();
 assert!((baseline.b-original.b).abs()>1e-6,"free-streaming stress generated by q!=0 affects b even if initial kappa zero");
}
#[test]
fn hamiltonian_constraint_radiation_and_source_monotonic_clock(){
 let x=bg(0.01,0.2);
 let curve=x.trajectory(500).unwrap();
 for r in curve.windows(2){
  assert!(r[1].elapsed_proper_s>r[0].elapsed_proper_s);
 }
 let c=cosm();
 for p in curve{
  let check=c.h0_per_s.powi(2)*(c.omega_m/p.a.powi(3)+c.omega_r*p.radiation_m/p.a.powi(4)+c.omega_lambda)+p.s_per_s*p.s_per_s;
  assert!((check/p.h_per_s.powi(2)-1.).abs()<1e-13);
  assert!(p.radiation_m>0.);
  assert!(p.s_over_h.abs()<0.03);
  assert!((p.pi_s_over_crit0/p.radiation_rho_over_crit0).abs()<1./3.);
 }
}
#[test]
fn numerical_refinement_and_domain_gates(){
 let bg=bg(0.01,0.2);
 let a=bg.endpoint(256).unwrap();let b=bg.endpoint(512).unwrap();let c=bg.endpoint(1024).unwrap();
 assert!((c.b-b.b).abs()<(b.b-a.b).abs()+1e-14);
 assert!((c.elapsed_proper_s/b.elapsed_proper_s-1.).abs()<3e-12);
 assert!(bg.trajectory(1).is_err());
 assert!(bg.trajectory(100000).is_err());
 assert!(bg.angular_moments(f64::NAN).is_err());
 assert!(bg.angular_moments(0.3).is_err());
}
